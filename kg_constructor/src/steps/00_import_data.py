from __future__ import annotations

import shutil
from pathlib import Path
from typing import Any, Dict

from kg_constructor.src.utils.log import get_logger

logger = get_logger(__name__)

# Supported source folders produced by MedJsonify
ENTITY_FOLDER_TYPES = ["xml_files", "csv_files", "txt_files"]


def import_entity_files_from_medjsonify(
    cfg: Dict[str, Any],
    paths,
    force: bool = False,
) -> None:
    """
    Import entity files generated by MedJsonify into the KG constructor input folder.

    This step copies the entity folders from:
        MedJsonify-main/NER/data/entities/

    into:
        kg_constructor/data/input/

    Supported folders:
        - xml_files
        - csv_files
        - txt_files

    Args:
        cfg: Pipeline configuration dictionary. It is kept for interface consistency,
            although it is not used in this step.
        paths: Object containing pipeline paths. Must provide `input_dir`.
        force: If True, existing destination folders are removed before copying.
    """
    inputs_cfg = cfg.get("inputs", {})
    source_root = Path(
        inputs_cfg.get(
            "medjsonify_entities_dir",
            "MedJsonify-main/NER/data/entities",
        )
    )
    destination_root = Path(paths.input_dir)

    destination_root.mkdir(parents=True, exist_ok=True)

    for folder_name in ENTITY_FOLDER_TYPES:
        source_folder = source_root / folder_name
        destination_folder = destination_root / folder_name

        if not source_folder.exists():
            logger.warning("Source folder not found: %s", source_folder)
            continue

        if destination_folder.exists():
            if force:
                logger.info("Removing existing destination folder: %s", destination_folder)
                shutil.rmtree(destination_folder)
            else:
                logger.info(
                    "Destination folder already exists: %s (use --force to overwrite)",
                    destination_folder,
                )
                continue

        logger.info("Copying %s -> %s", source_folder, destination_folder)
        shutil.copytree(source_folder, destination_folder)

    logger.info("Step 00 completed: entity files imported successfully.")


# Alias used by the pipeline runner
run = import_entity_files_from_medjsonify


if __name__ == "__main__":
    class Paths:
        input_dir = "kg_constructor/data/input"

    import_entity_files_from_medjsonify(cfg={}, paths=Paths(), force=True)