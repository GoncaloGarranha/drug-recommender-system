import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics.pairwise import cosine_similarity
from tqdm import tqdm

# Repository-relative path configuration.
SCRIPT_DIR = Path(__file__).resolve().parent
REPO_ROOT = SCRIPT_DIR.parents[2]

if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from tools.benchmark_tracker import log_experiment

def resolve_existing_path(*relative_candidates):
    """Return the first existing repository-relative path from the candidates."""
    for candidate in relative_candidates:
        candidate_path = (REPO_ROOT / candidate).resolve()
        if candidate_path.exists():
            return candidate_path
    searched = "\n".join(f"- {(REPO_ROOT / candidate).resolve()}" for candidate in relative_candidates)
    raise FileNotFoundError(f"Files not found:\n{searched}")

class ContentBasedBaseline:
    def __init__(self, triples_full_path, entity2id_path):
        print("--- [1/3] Initializing baseline V2 (TF-IDF + cosine) ---")
        
        # 1. Load the full triples file so we can extract ingredient information.
        df_all = pd.read_csv(triples_full_path)
        ingredients_df = df_all[df_all['rel'] == 'HAS_INGREDIENT'].copy()
        
        # 2. Load the entity-to-id mapping generated by the graph pipeline.
        with open(entity2id_path, 'r', encoding='utf-8') as f:
            self.entity2id = json.load(f)
            
        # 3. Build one text profile per drug by joining its ingredient identifiers.
        drug_data = (
            ingredients_df[ingredients_df['src'].isin(self.entity2id.keys())]
            .groupby('src')['dst']
            .apply(lambda x: " ".join(x))
            .reset_index()
        )
        
        if drug_data.empty:
            print("Critical error: no drug with ingredients was found in the entity2id mapping.")
            print(f"Example src value in the CSV: {ingredients_df['src'].iloc[0] if not ingredients_df.empty else 'N/A'}")
            sys.exit(1)

        self.drug_list = drug_data['src'].tolist()
        self.drug_to_idx = {drug: i for i, drug in enumerate(self.drug_list)}
        
        # 4. Vectorize the ingredient text using TF-IDF.
        # max_df=0.9 keeps tokens that are not present in almost every profile.
        # The token pattern accepts letters, numbers, and common identifier punctuation.
        self.vectorizer = TfidfVectorizer(
            max_df=0.9, 
            min_df=1, 
            token_pattern=r"[a-zA-Z0-9:]+" 
        )
        
        try:
            self.tfidf_matrix = self.vectorizer.fit_transform(drug_data['dst'])
        except ValueError as e:
            print(f"Vectorization error: {e}")
            print("Sample text passed to the vectorizer:", drug_data['dst'].iloc[0])
            sys.exit(1)
            
        print(f"-> TF-IDF matrix: {self.tfidf_matrix.shape} (drugs x features)")

    def predict_rankings(self, test_triples, train_triples):
        print("--- [2/3] Generating rankings with cosine similarity ---")
        
        # Map each disease to the indices of drugs associated with it in the training split.
        disease_to_train_indices = (
            train_triples[train_triples['rel'] == 'INDICATION']
            .groupby('dst')['src']
            .apply(lambda x: [self.drug_to_idx[d] for d in x if d in self.drug_to_idx])
            .to_dict()
        )

        results = []
        # Precompute the pairwise similarity matrix once for efficiency.
        similarity_matrix = cosine_similarity(self.tfidf_matrix)

        for _, row in tqdm(test_triples.iterrows(), total=len(test_triples)):
            target_drug = row['src']
            target_disease = row['dst']
            
            if target_drug not in self.drug_to_idx:
                continue

            target_idx = self.drug_to_idx[target_drug]
            known_indices = disease_to_train_indices.get(target_disease, [])
            
            if not known_indices:
                rank = 9999
            else:
                # Score each candidate by its best similarity to any known training drug for the disease.
                final_scores = np.max(similarity_matrix[:, known_indices], axis=1)
                
                # Convert scores into a descending rank order.
                sorted_indices = np.argsort(final_scores)[::-1]
                rank = np.where(sorted_indices == target_idx)[0][0] + 1
            
            results.append({'drug': target_drug, 'disease': target_disease, 'rank': rank})

        return pd.DataFrame(results)

if __name__ == "__main__":
    try:
        PATH_TRIPLES_FULL = resolve_existing_path("kg_constructor/data/output/triples/triples.csv")
        PATH_TRIPLES_FILTERED = resolve_existing_path("kg_constructor/data/output/triples/triples.filtered.csv")
        PATH_ENTITY2ID = resolve_existing_path("models/rgcn/data/processed/entity2id.json")
    except FileNotFoundError as e:
        print(e)
        sys.exit(1)

    # Use the filtered graph output to create a simple train/test split.
    df_filtered = pd.read_csv(PATH_TRIPLES_FILTERED)
    test_df = df_filtered.sample(frac=0.1, random_state=42)
    train_df = df_filtered.drop(test_df.index)

    model = ContentBasedBaseline(PATH_TRIPLES_FULL, PATH_ENTITY2ID)
    rankings = model.predict_rankings(test_df, train_df)

    # Final metrics.
    print("\n--- [3/3] Resultados Finais ---")
    hits_at_1 = (rankings['rank'] <= 1).mean()
    hits_at_3 = (rankings['rank'] <= 3).mean()
    hits_at_10 = (rankings['rank'] <= 10).mean()
    mrr = (1 / rankings['rank']).mean()

    print(f"Hits@1:  {hits_at_1:.4f}")
    print(f"Hits@3:  {hits_at_3:.4f}")
    print(f"Hits@10: {hits_at_10:.4f}")
    print(f"MRR:     {mrr:.4f}")

    log_experiment(
        model_name="Content-Based (TF-IDF baseline)",
        hits1=hits_at_1,
        hits3=hits_at_3,
        hits10=hits_at_10,
        mrr=mrr,
        notes="TF-IDF over HAS_INGREDIENT profiles; 90/10 split over filtered triples",
    )