def read_json(path: Path) -> Any:
    """Read a JSON file."""
    with path.open("r", encoding="utf-8") as file_obj:
        return json.load(file_obj)


def read_csv(path: Path) -> List[Dict[str, str]]:
    """Read a CSV file into a list of dictionaries."""
    with path.open("r", encoding="utf-8") as file_obj:
        return list(csv.DictReader(file_obj))


def find_latest_run(runs_dir: str) -> str:
    """
    Find the most recently modified run directory.
    """
    run_dirs = [path for path in glob.glob(os.path.join(runs_dir, "*")) if os.path.isdir(path)]
    if not run_dirs:
        raise FileNotFoundError(f"No run directories found in: {runs_dir}")

    run_dirs.sort(key=lambda path: os.path.getmtime(path), reverse=True)
    return run_dirs[0]


def load_prepared_graph(processed_dir: Path) -> Dict[str, Any]:
    """
    Load prepared graph artifacts generated by 00_prepare_graph.py.
    """
    required_files = {
        "entity2id": processed_dir / "entity2id.json",
        "id2entity": processed_dir / "id2entity.json",
        "rel2id": processed_dir / "rel2id.json",
        "id2rel": processed_dir / "id2rel.json",
        "entity_types": processed_dir / "entity_types.json",
        "triples_indexed": processed_dir / "triples_indexed.csv",
        "metadata": processed_dir / "graph_metadata.json",
    }

    missing = [str(path) for path in required_files.values() if not path.exists()]
    if missing:
        raise FileNotFoundError(
            "Missing prepared graph artifacts:\n" + "\n".join(missing)
        )

    return {
        "entity2id": read_json(required_files["entity2id"]),
        "id2entity": read_json(required_files["id2entity"]),
        "rel2id": read_json(required_files["rel2id"]),
        "id2rel": read_json(required_files["id2rel"]),
        "entity_types": read_json(required_files["entity_types"]),
        "triples": read_csv(required_files["triples_indexed"]),
        "metadata": read_json(required_files["metadata"]),
    }


def split_target_triples(
    triples: List[Dict[str, str]],
    target_relation: str,
    seed: int,
    train_ratio: float,
    val_ratio: float,
    test_ratio: float,
) -> Tuple[List[Dict[str, str]], List[Dict[str, str]], List[Dict[str, str]], List[Dict[str, str]]]:
    """
    Split target-relation triples into train/validation/test sets.

    Returns:
        train_target, valid_target, test_target, non_target_triples
    """
    if not np.isclose(train_ratio + val_ratio + test_ratio, 1.0):
        raise ValueError("Split ratios must sum to 1.0.")

    target_triples = [row for row in triples if (row.get("rel") or "").strip() == target_relation]
    non_target_triples = [row for row in triples if (row.get("rel") or "").strip() != target_relation]

    if not target_triples:
        raise ValueError(f"No triples found for target relation: {target_relation}")

    rng = random.Random(seed)
    rng.shuffle(target_triples)

    n_total = len(target_triples)
    n_train = int(n_total * train_ratio)
    n_val = int(n_total * val_ratio)

    train_target = target_triples[:n_train]
    valid_target = target_triples[n_train:n_train + n_val]
    test_target = target_triples[n_train + n_val:]

    return train_target, valid_target, test_target, non_target_triples


def build_training_graph(
    train_target: List[Dict[str, str]],
    non_target_triples: List[Dict[str, str]],
    context_relations: List[str],
    num_nodes: int,
    device: torch.device,
) -> Tuple[dgl.DGLGraph, torch.Tensor]:
    """
    Build the DGL graph used by the encoder.
    """
    graph_rows = list(train_target)

    allowed_context_relations = set(context_relations)
    for row in non_target_triples:
        relation = (row.get("rel") or "").strip()
        if relation in allowed_context_relations:
            graph_rows.append(row)

    src_ids = [int(row["src_id"]) for row in graph_rows]
    dst_ids = [int(row["dst_id"]) for row in graph_rows]
    rel_ids = [int(row["rel_id"]) for row in graph_rows]

    graph = dgl.graph((src_ids, dst_ids), num_nodes=num_nodes)
    edge_types = torch.tensor(rel_ids, dtype=torch.long, device=device)

    return graph.to(device), edge_types


def build_candidate_pool(
    entity_types: Dict[str, str],
    entity2id: Dict[str, int],
    candidate_entity_type: str,
    device: torch.device,
) -> torch.Tensor:
    """
    Build the candidate entity pool for ranking.
    """
    candidate_ids = sorted(
        entity2id[entity_id]
        for entity_id, entity_type in entity_types.items()
        if entity_type == candidate_entity_type
    )

    if not candidate_ids:
        raise ValueError(f"No candidate entities found for type: {candidate_entity_type}")

    return torch.tensor(candidate_ids, dtype=torch.long, device=device)


def build_known_positive_index(
    triples: List[Dict[str, str]],
    task_name: str,
) -> Dict[int, set]:
    """
    Build filtered-ranking lookup structures.

    Returns:
        Dictionary mapping query_id -> set(candidate_ids)
    """
    known = defaultdict(set)

    for row in triples:
        src_id = int(row["src_id"])
        dst_id = int(row["dst_id"])

        if task_name == "disease_to_drug":
            query_id = dst_id
            candidate_id = src_id
        elif task_name == "drug_to_disease":
            query_id = src_id
            candidate_id = dst_id
        else:
            raise ValueError(f"Unsupported task name: {task_name}")

        known[query_id].add(candidate_id)

    return known


def score_candidates(
    task_name: str,
    decoder: DistMultDecoder,
    node_embeddings: torch.Tensor,
    relation_id: int,
    query_id: int,
    candidate_ids: torch.Tensor,
    device: torch.device,
) -> torch.Tensor:
    """
    Score all candidate entities for a fixed query entity.
    """
    rel_emb = decoder.rel_emb(torch.tensor([relation_id], device=device)).repeat(len(candidate_ids), 1)

    if task_name == "disease_to_drug":
        disease_emb = node_embeddings[query_id].unsqueeze(0).repeat(len(candidate_ids), 1)
        drug_emb = node_embeddings[candidate_ids]
        scores = torch.sum(drug_emb * rel_emb * disease_emb, dim=1)
    elif task_name == "drug_to_disease":
        drug_emb = node_embeddings[query_id].unsqueeze(0).repeat(len(candidate_ids), 1)
        disease_emb = node_embeddings[candidate_ids]
        scores = torch.sum(drug_emb * rel_emb * disease_emb, dim=1)
    else:
        raise ValueError(f"Unsupported task name: {task_name}")

    return scores


@torch.no_grad()
def evaluate_ranking(
    encoder: RGCNEncoder,
    decoder: DistMultDecoder,
    graph: dgl.DGLGraph,
    edge_types: torch.Tensor,
    eval_triples: List[Dict[str, str]],
    relation_id: int,
    task_name: str,
    known_positives: Dict[int, set],
    candidate_ids: torch.Tensor,
    device: torch.device,
    hits_k: Tuple[int, ...] = (1, 3, 10),
) -> Dict[str, float]:
    """
    Evaluate filtered ranking metrics for the configured task.
    """
    encoder.eval()
    decoder.eval()

    node_embeddings = encoder(graph, edge_types)
    ranks = []
    hits = {k: 0 for k in hits_k}

    for row in eval_triples:
        src_id = int(row["src_id"])
        dst_id = int(row["dst_id"])

        if task_name == "disease_to_drug":
            query_id = dst_id
            true_candidate_id = src_id
        elif task_name == "drug_to_disease":
            query_id = src_id
            true_candidate_id = dst_id
        else:
            raise ValueError(f"Unsupported task name: {task_name}")

        scores = score_candidates(
            task_name=task_name,
            decoder=decoder,
            node_embeddings=node_embeddings,
            relation_id=relation_id,
            query_id=query_id,
            candidate_ids=candidate_ids,
            device=device,
        )

        known_candidates = known_positives.get(query_id, set())
        candidate_list = candidate_ids.tolist()

        for idx, candidate_id in enumerate(candidate_list):
            if candidate_id == true_candidate_id:
                continue
            if candidate_id in known_candidates:
                scores[idx] = -1e9

        true_mask = candidate_ids == true_candidate_id
        true_score = scores[true_mask].item()
        num_better = torch.sum(scores > true_score).item()
        num_equal = torch.sum(scores == true_score).item()
        rank = 1 + num_better + (num_equal - 1) / 2.0

        ranks.append(rank)
        for k in hits_k:
            if rank <= k:
                hits[k] += 1

    if not ranks:
        raise ValueError("No evaluation ranks were computed.")

    ranks = np.array(ranks, dtype=np.float64)

    return {
        "mrr": float(np.mean(1.0 / ranks)),
        **{f"hits@{k}": float(hits[k] / len(ranks)) for k in hits_k},
    }


def main() -> None:
    """
    Load a trained checkpoint and evaluate it on the validation or test split.
    """
    parser = argparse.ArgumentParser()
    parser.add_argument("--runs_dir", default="rgcn/runs")
    parser.add_argument("--run_dir", default=None)
    parser.add_argument("--split", default="test", choices=["valid", "test"])
    args = parser.parse_args()

    run_dir = args.run_dir if args.run_dir else find_latest_run(args.runs_dir)
    checkpoint_path = os.path.join(run_dir, "checkpoints", "best.pt")

    if not os.path.exists(checkpoint_path):
        raise FileNotFoundError(f"Checkpoint not found: {checkpoint_path}")

    checkpoint = torch.load(checkpoint_path, map_location="cpu")
    cfg = checkpoint["config"]

    seed = int(cfg.get("seed", 42))
    set_seed(seed)

    device = torch.device(cfg["training"].get("device", "cpu"))

    prepared = load_prepared_graph(Path(cfg["data"]["processed_dir"]))
    triples = prepared["triples"]
    entity2id = prepared["entity2id"]
    rel2id = prepared["rel2id"]
    entity_types = prepared["entity_types"]

    num_nodes = len(entity2id)
    num_relations = len(rel2id)

    task_cfg = cfg["task"]
    split_cfg = cfg["split"]

    task_name = task_cfg["name"]
    target_relation = task_cfg["target_relation"]
    candidate_entity_type = task_cfg["candidate_entity_type"]
    context_relations = task_cfg.get("context_relations", [target_relation])

    relation_id = rel2id.get(target_relation)
    if relation_id is None:
        raise ValueError(f"Target relation not found: {target_relation}")

    train_target, valid_target, test_target, non_target_triples = split_target_triples(
        triples=triples,
        target_relation=target_relation,
        seed=seed,
        train_ratio=float(split_cfg["train_ratio"]),
        val_ratio=float(split_cfg["val_ratio"]),
        test_ratio=float(split_cfg["test_ratio"]),
    )

    graph, edge_types = build_training_graph(
        train_target=train_target,
        non_target_triples=non_target_triples,
        context_relations=context_relations,
        num_nodes=num_nodes,
        device=device,
    )

    candidate_pool = build_candidate_pool(
        entity_types=entity_types,
        entity2id=entity2id,
        candidate_entity_type=candidate_entity_type,
        device=device,
    )

    known_positives = build_known_positive_index(
        triples=train_target + valid_target + test_target,
        task_name=task_name,
    )

    eval_triples = valid_target if args.split == "valid" else test_target

    encoder = RGCNEncoder(
        num_nodes,
        cfg["training"]["emb_dim"],
        num_relations,
        cfg["training"]["num_bases"],
        cfg["training"]["num_layers"],
        0.0,
    ).to(device)

    decoder = DistMultDecoder(
        num_relations,
        cfg["training"]["emb_dim"],
    ).to(device)

    encoder.load_state_dict(checkpoint["encoder"])
    decoder.load_state_dict(checkpoint["decoder"])

    results = evaluate_ranking(
        encoder=encoder,
        decoder=decoder,
        graph=graph,
        edge_types=edge_types,
        eval_triples=eval_triples,
        relation_id=relation_id,
        task_name=task_name,
        known_positives=known_positives,
        candidate_ids=candidate_pool,
        device=device,
        hits_k=tuple(cfg["training"]["hits_k"]),
    )

    print("-" * 60)
    print(f"RUN: {run_dir}")
    print(f"TASK: {task_name}")
    print(f"SPLIT: {args.split}")
    print("-" * 60)
    print(f"MRR: {results['mrr']:.4f}")
    for k in cfg["training"]["hits_k"]:
        print(f"Hits@{k}: {results[f'hits@{k}']:.4f}")
    print("-" * 60)

    log_experiment(
        model_name=f"R-GCN ({task_name})",
        hits1=results["hits@1"],
        hits3=results["hits@3"],
        hits10=results["hits@10"],
        mrr=results["mrr"],
        notes=f"Run: {Path(run_dir).name} | Split: {args.split}",
    )

    output_path = os.path.join(run_dir, f"final_metrics_{task_name}_{args.split}.json")
    with open(output_path, "w", encoding="utf-8") as file_obj:
        json.dump(results, file_obj, indent=2)

    print(f"Saved evaluation metrics to: {output_path}")


if __name__ == "__main__":
    main()