"""
Prepared graph validation script.

This script validates that all graph artifacts generated by prepare_graph.py
are correctly formatted and consistent for downstream R-GCN training.

Usage:
    python -m models.rgcn.src.load_data \
        --processed_dir models/rgcn/data/processed/disease_to_drug_full

Output:
    - Entity and relation counts
    - Triple counts
    - Entity type distribution
    - Relation distribution
    - Validation checks for mapping consistency
"""

from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path

from models.shared.io import read_csv, read_json


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--processed_dir", required=True)
    args = parser.parse_args()

    processed_dir = Path(args.processed_dir)

    entity2id_path = processed_dir / "entity2id.json"
    id2entity_path = processed_dir / "id2entity.json"
    rel2id_path = processed_dir / "rel2id.json"
    id2rel_path = processed_dir / "id2rel.json"
    entity_types_path = processed_dir / "entity_types.json"
    triples_indexed_path = processed_dir / "triples_indexed.csv"
    metadata_path = processed_dir / "graph_metadata.json"

    required_files = [
        entity2id_path,
        id2entity_path,
        rel2id_path,
        id2rel_path,
        entity_types_path,
        triples_indexed_path,
        metadata_path,
    ]

    missing_files = [path for path in required_files if not path.exists()]
    if missing_files:
        raise FileNotFoundError(
            "Missing required processed artifacts:\n"
            + "\n".join(str(path) for path in missing_files)
        )

    entity2id = read_json(entity2id_path)
    id2entity = read_json(id2entity_path)
    rel2id = read_json(rel2id_path)
    id2rel = read_json(id2rel_path)
    entity_types = read_json(entity_types_path)
    triples = read_csv(triples_indexed_path)
    metadata = read_json(metadata_path)

    # ---------------------------------------------------------------------
    # Vocabulary consistency checks
    # ---------------------------------------------------------------------
    assert len(entity2id) == len(id2entity), "entity2id and id2entity size mismatch"
    assert len(rel2id) == len(id2rel), "rel2id and id2rel size mismatch"

    for entity, entity_id in entity2id.items():
        recovered = id2entity.get(str(entity_id))
        assert recovered == entity, f"Inconsistent entity mapping: {entity} -> {entity_id}"

    for relation, relation_id in rel2id.items():
        recovered = id2rel.get(str(relation_id))
        assert recovered == relation, f"Inconsistent relation mapping: {relation} -> {relation_id}"

    missing_entity_types = [entity for entity in entity2id if entity not in entity_types]
    assert not missing_entity_types, "Some entities are missing type assignments"

    # ---------------------------------------------------------------------
    # Triple consistency checks
    # ---------------------------------------------------------------------
    relation_counter = Counter()
    entity_type_counter = Counter(entity_types.values())

    for row in triples:
        src_id = row["src_id"]
        rel_id = row["rel_id"]
        dst_id = row["dst_id"]

        src = row["src"]
        rel = row["rel"]
        dst = row["dst"]

        assert id2entity.get(str(src_id)) == src, f"Invalid src mapping for row: {row}"
        assert id2entity.get(str(dst_id)) == dst, f"Invalid dst mapping for row: {row}"
        assert id2rel.get(str(rel_id)) == rel, f"Invalid rel mapping for row: {row}"

        relation_counter[rel] += 1

    print("Prepared graph artifacts loaded successfully.")
    print(f"Entities: {len(entity2id)}")
    print(f"Relations: {len(rel2id)}")
    print(f"Triples: {len(triples)}")
    print(f"Entity types: {dict(entity_type_counter)}")
    print(f"Relation distribution: {dict(relation_counter)}")
    print("Metadata summary:")
    print(json.dumps(metadata, indent=2, ensure_ascii=False))


if __name__ == "__main__":
    main()