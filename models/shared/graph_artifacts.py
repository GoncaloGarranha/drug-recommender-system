from __future__ import annotations

from pathlib import Path
from typing import Any, Dict

from .io import read_csv, read_json


def _has_required_artifacts(processed_dir: Path) -> bool:
	required = [
		processed_dir / "entity2id.json",
		processed_dir / "id2entity.json",
		processed_dir / "rel2id.json",
		processed_dir / "id2rel.json",
		processed_dir / "entity_types.json",
		processed_dir / "triples_indexed.csv",
		processed_dir / "graph_metadata.json",
	]
	return all(path.exists() for path in required)


def resolve_processed_dir(processed_dir: str | Path, task_name: str | None = None) -> Path:
	"""Resolve processed_dir across old/new config layouts.

	Supports backward compatibility for older runs that stored paths such as
	`rgcn/data/processed` while current configs use `models/rgcn/data/processed/<task>`.
	"""
	base = Path(processed_dir)
	candidates: list[Path] = [base]

	if not base.is_absolute():
		candidates.append(Path("models") / base)

	if base.parts and base.parts[0] == "rgcn":
		legacy_mapped = Path("models") / Path(*base.parts)
		candidates.append(legacy_mapped)

	if task_name:
		extra: list[Path] = []
		for candidate in list(candidates):
			if candidate.name != task_name:
				extra.append(candidate / task_name)
		candidates.extend(extra)

	seen = set()
	ordered_candidates: list[Path] = []
	for candidate in candidates:
		candidate = Path(candidate)
		key = str(candidate)
		if key not in seen:
			seen.add(key)
			ordered_candidates.append(candidate)

	for candidate in ordered_candidates:
		if _has_required_artifacts(candidate):
			return candidate

	return base


def validate_processed_artifacts(processed_dir: str | Path) -> Dict[str, Path]:
	"""
	Validate that all required graph artifacts exist.
	
	Returns a dictionary of validated file paths.
	Raises FileNotFoundError if any required files are missing.
	"""
	processed_dir = Path(processed_dir)
	
	required_files = {
		"entity2id": processed_dir / "entity2id.json",
		"id2entity": processed_dir / "id2entity.json",
		"rel2id": processed_dir / "rel2id.json",
		"id2rel": processed_dir / "id2rel.json",
		"entity_types": processed_dir / "entity_types.json",
		"triples_indexed": processed_dir / "triples_indexed.csv",
		"metadata": processed_dir / "graph_metadata.json",
	}

	missing = [str(path) for path in required_files.values() if not path.exists()]
	if missing:
		raise FileNotFoundError(
			"Missing prepared graph artifacts:\n" + "\n".join(missing)
		)
	
	return required_files


def load_prepared_graph(processed_dir: str | Path) -> Dict[str, Any]:
	"""
	Load prepared graph artifacts generated by 00_prepare_graph.py.
	
	Returns a dictionary with keys:
		- entity2id: Dict[str, int]
		- id2entity: Dict[int, str]
		- rel2id: Dict[str, int]
		- id2rel: Dict[int, str]
		- entity_types: Dict[str, str]
		- triples: List[Dict[str, str]]
		- metadata: Dict[str, Any]
	"""
	processed_dir = Path(processed_dir)
	required_files = validate_processed_artifacts(processed_dir)

	return {
		"entity2id": read_json(required_files["entity2id"]),
		"id2entity": read_json(required_files["id2entity"]),
		"rel2id": read_json(required_files["rel2id"]),
		"id2rel": read_json(required_files["id2rel"]),
		"entity_types": read_json(required_files["entity_types"]),
		"triples": read_csv(required_files["triples_indexed"]),
		"metadata": read_json(required_files["metadata"]),
	}
