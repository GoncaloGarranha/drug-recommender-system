"""
R-GCN Training Script

Train an R-GCN encoder with a DistMult decoder for configurable link prediction
tasks over a prepared knowledge graph.

Supported task modes:
    - disease_to_drug
    - drug_to_disease

Usage:
    python -m rgcn.src.02_train --config rgcn/configs/disease_to_drug.yaml
"""

from __future__ import annotations

import argparse
import csv
import json
import os
import random
import time
from collections import defaultdict
from pathlib import Path
from typing import Any, Dict, List, Tuple

import dgl
import numpy as np
import torch
import torch.nn.functional as F
import yaml

from rgcn.src.models.decoders import DistMultDecoder
from rgcn.src.models.rgcn_encoder import RGCNEncoder
from rgcn.src.utils.seed import set_seed


def ensure_dir(path: str) -> None:
    """Create a directory if it does not exist."""
    os.makedirs(path, exist_ok=True)


def timestamp() -> str:
    """Return the current timestamp in YYYY-MM-DD_HH-MM-SS format."""
    return time.strftime("%Y-%m-%d_%H-%M-%S")


def read_json(path: Path) -> Any:
    """Read a JSON file."""
    with path.open("r", encoding="utf-8") as file_obj:
        return json.load(file_obj)


def read_csv(path: Path) -> List[Dict[str, str]]:
    """Read a CSV file into a list of dictionaries."""
    with path.open("r", encoding="utf-8") as file_obj:
        return list(csv.DictReader(file_obj))


def load_prepared_graph(data_cfg: Dict[str, Any]) -> Dict[str, Any]:
    """
    Load prepared graph artifacts generated by 00_prepare_graph.py.
    """
    processed_dir = Path(data_cfg["processed_dir"])

    required_files = {
        "entity2id": processed_dir / "entity2id.json",
        "id2entity": processed_dir / "id2entity.json",
        "rel2id": processed_dir / "rel2id.json",
        "id2rel": processed_dir / "id2rel.json",
        "entity_types": processed_dir / "entity_types.json",
        "triples_indexed": processed_dir / "triples_indexed.csv",
        "metadata": processed_dir / "graph_metadata.json",
    }

    missing = [str(path) for path in required_files.values() if not path.exists()]
    if missing:
        raise FileNotFoundError(
            "Missing prepared graph artifacts:\n" + "\n".join(missing)
        )

    return {
        "entity2id": read_json(required_files["entity2id"]),
        "id2entity": read_json(required_files["id2entity"]),
        "rel2id": read_json(required_files["rel2id"]),
        "id2rel": read_json(required_files["id2rel"]),
        "entity_types": read_json(required_files["entity_types"]),
        "triples": read_csv(required_files["triples_indexed"]),
        "metadata": read_json(required_files["metadata"]),
    }


def split_target_triples(
    triples: List[Dict[str, str]],
    target_relation: str,
    seed: int,
    train_ratio: float,
    val_ratio: float,
    test_ratio: float,
) -> Tuple[List[Dict[str, str]], List[Dict[str, str]], List[Dict[str, str]], List[Dict[str, str]]]:
    """
    Split target-relation triples into train/validation/test sets.

    Returns:
        train_target, valid_target, test_target, non_target_triples
    """
    if not np.isclose(train_ratio + val_ratio + test_ratio, 1.0):
        raise ValueError("Split ratios must sum to 1.0.")

    target_triples = [row for row in triples if (row.get("rel") or "").strip() == target_relation]
    non_target_triples = [row for row in triples if (row.get("rel") or "").strip() != target_relation]

    if not target_triples:
        raise ValueError(f"No triples found for target relation: {target_relation}")

    rng = random.Random(seed)
    rng.shuffle(target_triples)

    n_total = len(target_triples)
    n_train = int(n_total * train_ratio)
    n_val = int(n_total * val_ratio)

    train_target = target_triples[:n_train]
    valid_target = target_triples[n_train:n_train + n_val]
    test_target = target_triples[n_train + n_val:]

    return train_target, valid_target, test_target, non_target_triples


def build_training_graph(
    train_target: List[Dict[str, str]],
    non_target_triples: List[Dict[str, str]],
    context_relations: List[str],
    num_nodes: int,
    device: torch.device,
) -> Tuple[dgl.DGLGraph, torch.Tensor]:
    """
    Build the DGL graph used by the encoder.

    The training graph contains:
        - train triples from the target relation
        - non-target triples whose relation is allowed as structural context
    """
    graph_rows = list(train_target)

    allowed_context_relations = set(context_relations)
    for row in non_target_triples:
        relation = (row.get("rel") or "").strip()
        if relation in allowed_context_relations:
            graph_rows.append(row)

    src_ids = [int(row["src_id"]) for row in graph_rows]
    dst_ids = [int(row["dst_id"]) for row in graph_rows]
    rel_ids = [int(row["rel_id"]) for row in graph_rows]

    graph = dgl.graph((src_ids, dst_ids), num_nodes=num_nodes)
    edge_types = torch.tensor(rel_ids, dtype=torch.long, device=device)

    return graph.to(device), edge_types


def build_candidate_pool(
    entity_types: Dict[str, str],
    entity2id: Dict[str, int],
    candidate_entity_type: str,
    device: torch.device,
) -> torch.Tensor:
    """
    Build the candidate entity pool for ranking.
    """
    candidate_ids = sorted(
        entity2id[entity]
        for entity, entity_type in entity_types.items()
        if entity_type == candidate_entity_type
    )

    if not candidate_ids:
        raise ValueError(f"No candidate entities found for type: {candidate_entity_type}")

    return torch.tensor(candidate_ids, dtype=torch.long, device=device)


def build_known_positive_index(
    triples: List[Dict[str, str]],
    task_name: str,
) -> Dict[int, set]:
    """
    Build filtered-ranking lookup structures.

    Returns:
        Dictionary mapping query_id -> set(candidate_ids)
    """
    known = defaultdict(set)

    for row in triples:
        src_id = int(row["src_id"])
        dst_id = int(row["dst_id"])

        if task_name == "disease_to_drug":
            query_id = dst_id
            candidate_id = src_id
        elif task_name == "drug_to_disease":
            query_id = src_id
            candidate_id = dst_id
        else:
            raise ValueError(f"Unsupported task name: {task_name}")

        known[query_id].add(candidate_id)

    return known


def score_candidates(
    task_name: str,
    decoder: DistMultDecoder,
    node_embeddings: torch.Tensor,
    relation_id: int,
    query_id: int,
    candidate_ids: torch.Tensor,
    device: torch.device,
) -> torch.Tensor:
    """
    Score all candidate entities for a fixed query entity.
    """
    rel_emb = decoder.rel_emb(torch.tensor([relation_id], device=device)).repeat(len(candidate_ids), 1)

    if task_name == "disease_to_drug":
        disease_emb = node_embeddings[query_id].unsqueeze(0).repeat(len(candidate_ids), 1)
        drug_emb = node_embeddings[candidate_ids]
        scores = torch.sum(drug_emb * rel_emb * disease_emb, dim=1)
    elif task_name == "drug_to_disease":
        drug_emb = node_embeddings[query_id].unsqueeze(0).repeat(len(candidate_ids), 1)
        disease_emb = node_embeddings[candidate_ids]
        scores = torch.sum(drug_emb * rel_emb * disease_emb, dim=1)
    else:
        raise ValueError(f"Unsupported task name: {task_name}")

    return scores


@torch.no_grad()
def evaluate_ranking(
    encoder: RGCNEncoder,
    decoder: DistMultDecoder,
    graph: dgl.DGLGraph,
    edge_types: torch.Tensor,
    eval_triples: List[Dict[str, str]],
    relation_id: int,
    task_name: str,
    known_positives: Dict[int, set],
    candidate_ids: torch.Tensor,
    device: torch.device,
    hits_k: Tuple[int, ...] = (1, 3, 10),
) -> Dict[str, float]:
    """
    Evaluate filtered ranking metrics for the configured task.
    """
    encoder.eval()
    decoder.eval()

    node_embeddings = encoder(graph, edge_types)
    ranks = []
    hits = {k: 0 for k in hits_k}

    for row in eval_triples:
        src_id = int(row["src_id"])
        dst_id = int(row["dst_id"])

        if task_name == "disease_to_drug":
            query_id = dst_id
            true_candidate_id = src_id
        elif task_name == "drug_to_disease":
            query_id = src_id
            true_candidate_id = dst_id
        else:
            raise ValueError(f"Unsupported task name: {task_name}")

        scores = score_candidates(
            task_name=task_name,
            decoder=decoder,
            node_embeddings=node_embeddings,
            relation_id=relation_id,
            query_id=query_id,
            candidate_ids=candidate_ids,
            device=device,
        )

        known_candidates = known_positives.get(query_id, set())
        candidate_list = candidate_ids.tolist()

        for idx, candidate_id in enumerate(candidate_list):
            if candidate_id == true_candidate_id:
                continue
            if candidate_id in known_candidates:
                scores[idx] = -1e9

        true_mask = candidate_ids == true_candidate_id
        true_score = scores[true_mask].item()
        num_better = torch.sum(scores > true_score).item()
        num_equal = torch.sum(scores == true_score).item()
        rank = 1 + num_better + (num_equal - 1) / 2.0

        ranks.append(rank)
        for k in hits_k:
            if rank <= k:
                hits[k] += 1

    if not ranks:
        raise ValueError("No evaluation ranks were computed.")

    ranks = np.array(ranks, dtype=np.float64)

    return {
        "mrr": float(np.mean(1.0 / ranks)),
        **{f"hits@{k}": float(hits[k] / len(ranks)) for k in hits_k},
    }


def build_training_pairs(
    train_triples: List[Dict[str, str]],
    task_name: str,
    device: torch.device,
) -> Tuple[torch.Tensor, torch.Tensor]:
    """
    Build training query/candidate pairs for the configured task.

    Returns:
        positives_query, positives_candidate
    """
    queries = []
    candidates = []

    for row in train_triples:
        src_id = int(row["src_id"])
        dst_id = int(row["dst_id"])

        if task_name == "disease_to_drug":
            queries.append(dst_id)
            candidates.append(src_id)
        elif task_name == "drug_to_disease":
            queries.append(src_id)
            candidates.append(dst_id)
        else:
            raise ValueError(f"Unsupported task name: {task_name}")

    return (
        torch.tensor(queries, dtype=torch.long, device=device),
        torch.tensor(candidates, dtype=torch.long, device=device),
    )


def negative_sampling(
    positive_queries: torch.Tensor,
    relation_id: int,
    k: int,
    candidate_pool: torch.Tensor,
    device: torch.device,
) -> Tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
    """
    Generate negative samples by corrupting the candidate entity.
    """
    batch_size = positive_queries.shape[0]
    negative_candidates = candidate_pool[
        torch.randint(0, len(candidate_pool), (batch_size * k,), device=device)
    ]
    negative_relations = torch.full((batch_size * k,), relation_id, dtype=torch.long, device=device)
    negative_queries = positive_queries.repeat_interleave(k)

    return negative_queries, negative_relations, negative_candidates


def score_training_batch(
    task_name: str,
    decoder: DistMultDecoder,
    node_embeddings: torch.Tensor,
    queries: torch.Tensor,
    relation_id: int,
    candidates: torch.Tensor,
) -> torch.Tensor:
    """
    Score training triples according to the configured task direction.
    """
    relation_tensor = torch.full_like(queries, relation_id)
    rel_emb = decoder.rel_emb(relation_tensor)

    if task_name == "disease_to_drug":
        drug_emb = node_embeddings[candidates]
        disease_emb = node_embeddings[queries]
        return torch.sum(drug_emb * rel_emb * disease_emb, dim=1)

    if task_name == "drug_to_disease":
        drug_emb = node_embeddings[queries]
        disease_emb = node_embeddings[candidates]
        return torch.sum(drug_emb * rel_emb * disease_emb, dim=1)

    raise ValueError(f"Unsupported task name: {task_name}")


def save_yaml(path: str, data: Dict[str, Any]) -> None:
    """Save a YAML file."""
    with open(path, "w", encoding="utf-8") as file_obj:
        yaml.safe_dump(data, file_obj, sort_keys=False, allow_unicode=True)


def save_json(path: str, data: Any) -> None:
    """Save a JSON file."""
    with open(path, "w", encoding="utf-8") as file_obj:
        json.dump(data, file_obj, indent=2, ensure_ascii=False)


def main() -> None:
    """
    Run the training pipeline and save the best checkpoint according to
    validation MRR.
    """
    parser = argparse.ArgumentParser()
    parser.add_argument("--config", default="rgcn/configs/disease_to_drug.yaml")
    args = parser.parse_args()

    with open(args.config, "r", encoding="utf-8") as file_obj:
        cfg = yaml.safe_load(file_obj)

    seed = int(cfg.get("seed", 42))
    set_seed(seed)

    device = torch.device(cfg["training"].get("device", "cpu"))

    prepared = load_prepared_graph(cfg["data"])
    triples = prepared["triples"]
    entity2id = prepared["entity2id"]
    rel2id = prepared["rel2id"]
    entity_types = prepared["entity_types"]

    num_nodes = len(entity2id)
    num_relations = len(rel2id)

    task_cfg = cfg["task"]
    split_cfg = cfg["split"]

    task_name = task_cfg["name"]
    target_relation = task_cfg["target_relation"]
    candidate_entity_type = task_cfg["candidate_entity_type"]
    context_relations = task_cfg.get("context_relations", [target_relation])

    relation_id = rel2id.get(target_relation)
    if relation_id is None:
        raise ValueError(f"Target relation not found: {target_relation}")

    train_target, valid_target, test_target, non_target_triples = split_target_triples(
        triples=triples,
        target_relation=target_relation,
        seed=seed,
        train_ratio=float(split_cfg["train_ratio"]),
        val_ratio=float(split_cfg["val_ratio"]),
        test_ratio=float(split_cfg["test_ratio"]),
    )

    graph, edge_types = build_training_graph(
        train_target=train_target,
        non_target_triples=non_target_triples,
        context_relations=context_relations,
        num_nodes=num_nodes,
        device=device,
    )

    candidate_pool = build_candidate_pool(
        entity_types=entity_types,
        entity2id=entity2id,
        candidate_entity_type=candidate_entity_type,
        device=device,
    )

    known_positives = build_known_positive_index(
        triples=train_target + valid_target + test_target,
        task_name=task_name,
    )

    train_queries, train_candidates = build_training_pairs(
        train_triples=train_target,
        task_name=task_name,
        device=device,
    )

    encoder = RGCNEncoder(
        num_nodes,
        cfg["training"]["emb_dim"],
        num_relations,
        cfg["training"]["num_bases"],
        cfg["training"]["num_layers"],
        cfg["training"]["dropout"],
    ).to(device)

    decoder = DistMultDecoder(
        num_relations,
        cfg["training"]["emb_dim"],
    ).to(device)

    optimizer = torch.optim.Adam(
        list(encoder.parameters()) + list(decoder.parameters()),
        lr=cfg["training"]["lr"],
        weight_decay=cfg["training"]["weight_decay"],
    )

    run_dir = os.path.join(cfg["runs"]["out_dir"], f"{timestamp()}_{task_name}")
    checkpoints_dir = os.path.join(run_dir, "checkpoints")
    ensure_dir(run_dir)
    ensure_dir(checkpoints_dir)

    save_yaml(os.path.join(run_dir, "config.yaml"), cfg)

    split_summary = {
        "task_name": task_name,
        "target_relation": target_relation,
        "train_size": len(train_target),
        "valid_size": len(valid_target),
        "test_size": len(test_target),
        "num_nodes": num_nodes,
        "num_relations": num_relations,
        "candidate_pool_size": int(len(candidate_pool)),
        "context_relations": context_relations,
    }
    save_json(os.path.join(run_dir, "split_summary.json"), split_summary)

    print(f"Task: {task_name} | Target relation: {target_relation} | Device: {device}")
    print(
        f"Split sizes | train={len(train_target)} | valid={len(valid_target)} | test={len(test_target)}"
    )

    best_mrr = -1.0
    best_epoch = -1
    train_log: List[Dict[str, Any]] = []

    for epoch in range(1, cfg["training"]["epochs"] + 1):
        encoder.train()
        decoder.train()

        node_embeddings = encoder(graph, edge_types)

        positive_scores = score_training_batch(
            task_name=task_name,
            decoder=decoder,
            node_embeddings=node_embeddings,
            queries=train_queries,
            relation_id=relation_id,
            candidates=train_candidates,
        )

        negative_queries, negative_relations, negative_candidates = negative_sampling(
            positive_queries=train_queries,
            relation_id=relation_id,
            k=cfg["training"]["neg_k"],
            candidate_pool=candidate_pool,
            device=device,
        )

        negative_scores = score_training_batch(
            task_name=task_name,
            decoder=decoder,
            node_embeddings=node_embeddings,
            queries=negative_queries,
            relation_id=relation_id,
            candidates=negative_candidates,
        )

        loss = (
            F.binary_cross_entropy_with_logits(
                positive_scores,
                torch.ones_like(positive_scores),
            )
            + F.binary_cross_entropy_with_logits(
                negative_scores,
                torch.zeros_like(negative_scores),
            )
        )

        optimizer.zero_grad()
        loss.backward()
        optimizer.step()

        log_entry: Dict[str, Any] = {
            "epoch": epoch,
            "loss": float(loss.item()),
            "valid_mrr": None,
        }

        if epoch % cfg["training"]["eval_every"] == 0 or epoch == cfg["training"]["epochs"]:
            metrics = evaluate_ranking(
                encoder=encoder,
                decoder=decoder,
                graph=graph,
                edge_types=edge_types,
                eval_triples=valid_target,
                relation_id=relation_id,
                task_name=task_name,
                known_positives=known_positives,
                candidate_ids=candidate_pool,
                device=device,
                hits_k=tuple(cfg["training"]["hits_k"]),
            )

            log_entry["valid_mrr"] = float(metrics["mrr"])
            for k in cfg["training"]["hits_k"]:
                log_entry[f"valid_hits@{k}"] = float(metrics[f"hits@{k}"])

            print(
                f"Epoch {epoch:04d} | Loss: {loss.item():.4f} | "
                f"Valid MRR: {metrics['mrr']:.4f}"
            )

            if metrics["mrr"] > best_mrr:
                best_mrr = float(metrics["mrr"])
                best_epoch = epoch

                torch.save(
                    {
                        "encoder": encoder.state_dict(),
                        "decoder": decoder.state_dict(),
                        "config": cfg,
                        "task_name": task_name,
                        "target_relation": target_relation,
                        "best_epoch": best_epoch,
                        "best_valid_mrr": best_mrr,
                    },
                    os.path.join(checkpoints_dir, "best.pt"),
                )

                best_metrics = {
                    "best_epoch": best_epoch,
                    "best_valid_mrr": best_mrr,
                    **{f"best_valid_hits@{k}": float(metrics[f"hits@{k}"]) for k in cfg["training"]["hits_k"]},
                }
                save_json(os.path.join(run_dir, "best_metrics.json"), best_metrics)

        train_log.append(log_entry)

    torch.save(
        {
            "encoder": encoder.state_dict(),
            "decoder": decoder.state_dict(),
            "config": cfg,
            "task_name": task_name,
            "target_relation": target_relation,
            "final_epoch": cfg["training"]["epochs"],
            "best_epoch": best_epoch,
            "best_valid_mrr": best_mrr,
        },
        os.path.join(checkpoints_dir, "last.pt"),
    )

    save_json(os.path.join(run_dir, "train_log.json"), train_log)

    print(f"Training complete. Best validation MRR: {best_mrr:.4f} (epoch {best_epoch})")


if __name__ == "__main__":
    main()